local t = require("modules/v2_test/testlib")
local tile_core = require("modules/gridworld/tile_core")
local border_core = require("modules/gridworld/border_core")
local tile = require("modules/gridworld/tile")

-- Sinks (cross-border biters spec §4, plan Task 3). Each case's surface gets a gridworld record as the config would make
-- it: tile (0, 0) of T = 128, so its chunks are -2..1 on each axis and the second outside row is ring 2.
local T = 128

local function record(name)
	storage.gridworld.tiles[name] = { world = "bt", x = 0, y = 0, size = T, surface = name, seed = 1,
		x1 = -T / 2, y1 = -T / 2, x2 = T / 2, y2 = T / 2, swept = true }
end

local function surface_of(name)
	return game.create_surface(name, { seed = 20200, autoplace_controls = { ["enemy-base"] = { size = 0 } } })
end

local function sinks(surface, cx, cy)
	return surface.count_entities_filtered({ name = border_core.SINK,
		area = { { cx * 32, cy * 32 }, { cx * 32 + 32, cy * 32 + 32 } } })
end

--- Run fn once no chunk of surface name waits in gridworld's cleanup queue (one chunk a tick, every surface's).
local function drained(ctx, offset, name, fn)
	ctx.at(offset, function()
		for _, c in pairs(storage.gridworld.cleanup) do
			if c.surface == name then
				drained(ctx, offset + 50, name, fn)
				return
			end
		end
		fn()
	end)
end

t.case("sinks: one in each chunk of the second outside row, corners included, none elsewhere; a second cleanup adds none",
	function(ctx)
		local S = "bt-sinks"
		ctx.at(5, function()
			local surface = surface_of(S)
			record(S)
			surface.request_to_generate_chunks({ 0, 0 }, 5)
			surface.force_generate_chunk_requests()
		end)
		drained(ctx, 100, S, function()
			local surface, rec = game.surfaces[S], storage.gridworld.tiles[S]
			local wrong, ring2 = 0, 0
			for cx = -5, 4 do
				for cy = -5, 4 do
					local r = tile_core.ring(rec, cx, cy)
					ring2 = ring2 + (r == 2 and 1 or 0)
					if sinks(surface, cx, cy) ~= (r == 2 and 1 or 0) then
						wrong = wrong + 1
					end
				end
			end
			ctx.expect(ring2 == 28 and wrong == 0, "28 ring-2 chunks with one sink each, none elsewhere; " .. wrong .. " wrong")
			tile.clean_chunk(S, 3, 0)
			ctx.expect(sinks(surface, 3, 0) == 1, "a second cleanup of a ring-2 chunk keeps its one sink")
			local p = prototypes.entity[border_core.SINK]
			ctx.expect(p.get_max_health() == 1000000 and p.emissions_per_second.pollution == -5000, "the prototype")
		end)
	end)

--- How many chunks east of ring 5 (cx 6..12, cy -8..8) are generated.
local function beyond(surface)
	local n = 0
	for cx = 6, 12 do
		for cy = -8, 8 do
			n = n + (surface.is_chunk_generated({ cx, cy }) and 1 or 0)
		end
	end
	return n
end

t.case("sinks: 100000 pushed into the first row every 64 ticks leaves ring 3 at 0 and generates nothing new past the "
	.. "block (spike 27 K1 c)", function(ctx)
	local S = "bt-push"
	local most, before = 0, nil
	ctx.at(5, function()
		local surface = surface_of(S)
		record(S)
		surface.request_to_generate_chunks({ 0, 0 }, 5)
		surface.force_generate_chunk_requests()
	end)
	drained(ctx, 100, S, function()
		before = beyond(game.surfaces[S])
		local start = game.tick - ctx.first_tick
		for k = 0, 19 do
			ctx.at(start + 1 + k * 64, function()
				for cy = -2, 1 do
					game.surfaces[S].set_pollution({ 2 * 32 + 16, cy * 32 + 16 }, 100000)
				end
			end)
		end
		for k = 1, 90 do
			ctx.at(start + k * 16, function()
				for cy = -2, 1 do
					most = math.max(most, game.surfaces[S].get_pollution({ 4 * 32 + 16, cy * 32 + 16 }))
				end
			end)
		end
		ctx.at(start + 1500, function()
			ctx.expect(most == 0, "ring 3 east stayed at 0; it reached " .. most)
			ctx.expect(beyond(game.surfaces[S]) == before, "no chunk east of ring 5 was generated by the push")
		end)
	end)
end)

t.case("sinks: none on a planet without a pollutant (Vulcanus), Gleba has them for its spores (spike 34 G1)", function(ctx)
	ctx.at(5, function()
		for _, name in ipairs({ "vulcanus", "gleba" }) do
			local surface = game.get_surface(name) or game.planets[name].create_surface() -- border_game_test may make it first
			record(name)
			surface.request_to_generate_chunks({ 0, 0 }, 5)
			surface.force_generate_chunk_requests()
		end
	end)
	drained(ctx, 100, "vulcanus", function()
		drained(ctx, game.tick - ctx.first_tick + 1, "gleba", function()
			ctx.expect(game.surfaces.vulcanus.count_entities_filtered({ name = border_core.SINK }) == 0, "vulcanus: no sink")
			ctx.expect(game.surfaces.gleba.count_entities_filtered({ name = border_core.SINK }) == 28,
				"gleba: one sink in each of its 28 second-row chunks")
		end)
	end)
end)
