local t = require("modules/v2_test/testlib")
local loop = require("modules/v2_test/loopback")
local border = require("modules/gridworld/border")
local border_core = require("modules/gridworld/border_core")
local cloud = require("modules/gridworld/cloud")
local cloud_core = require("modules/gridworld/cloud_core")

-- Gleba (cross-border biters plan Task 13, spike 34): its spores are swept, sunk and raided as Nauvis's pollution. Every
-- case shares the record the sinks case gives Gleba at tick 5 (tile (0, 0) of T = 128: a surface has one record), and
-- starts at tick 300 or later, once the sinks are in: the push case at 300 on the east strip, the raid case at 2000 on
-- a strip of its own, after the push case's edge-free run.
local T = 128

local TOWERS = { { 28.5, 10.5 }, { 28.5, 16.5 } }

local function gleba()
	local surface = game.get_surface("gleba") or game.planets.gleba.create_surface()
	storage.gridworld.tiles.gleba = { world = "bt", x = 0, y = 0, size = T, surface = "gleba", seed = 1,
		x1 = -T / 2, y1 = -T / 2, x2 = T / 2, y2 = T / 2, swept = true }
	surface.request_to_generate_chunks({ 0, 0 }, 5)
	surface.force_generate_chunk_requests()
	return surface
end

--- How many chunks east of ring 5 (cx 6..12, cy -8..8) are generated.
local function beyond(surface)
	local n = 0
	for cx = 6, 12 do
		for cy = -8, 8 do
			n = n + (surface.is_chunk_generated({ cx, cy }) and 1 or 0)
		end
	end
	return n
end

t.case("gleba: 100000 spores pushed into the first row every 64 ticks leave ring 3 at 0 and generate nothing new past "
	.. "the block (spike 34 G1)", function(ctx)
	local most, before = 0, nil
	ctx.at(5, gleba)
	ctx.at(300, function()
		local surface = game.surfaces.gleba
		loop.ground(64, -128, 190, 127, "gleba") -- Gleba's own enemies would eat the spores
		before = beyond(surface)
		local start = game.tick - ctx.first_tick
		for k = 0, 19 do
			ctx.at(start + 1 + k * 64, function()
				for cy = -2, 1 do
					surface.set_pollution({ 2 * 32 + 16, cy * 32 + 16 }, 100000)
				end
			end)
		end
		for k = 1, 90 do
			ctx.at(start + k * 16, function()
				for cy = -2, 1 do
					most = math.max(most, surface.get_pollution({ 4 * 32 + 16, cy * 32 + 16 }))
				end
			end)
		end
		ctx.at(start + 1500, function()
			ctx.expect(most == 0, "ring 3 east stayed at 0; it reached " .. most)
			ctx.expect(beyond(surface) == before, "no chunk east of ring 5 was generated by the push")
			ctx.expect(surface.count_entities_filtered({ name = border_core.SINK, area = { { 96, -64 }, { 128, 64 } } }) == 4,
				"the east second row's four sinks held it")
		end)
	end)
end)

--- Polls from offset until tick 4500 for the raid's units out by Gleba's east line (the oracle's own units, outside the
--- tile, don't count); calls fn with them.
local function landed(ctx, offset, fn)
	ctx.at(offset, function()
		local found = {}
		for _, e in ipairs(game.surfaces.gleba.find_entities_filtered({ area = { { 48, -16 }, { 64, 32 } }, force = "enemy" })) do
			if (e.type == "unit" or e.type == "spider-unit") and not e.name:find("oracle", 1, true) then
				found[#found + 1] = e
			end
		end
		if #found == 0 and offset < 4500 then
			return landed(ctx, offset + 20, fn)
		end
		fn(found)
	end)
end

t.case("gleba: a gleba-spawner takes 20 + 0.01 v of spores, and its raid, of units vanilla sends on attacks only (no "
	.. "wrigglers), comes out by the east line (spike 34 G3, G4)", function(ctx)
	local ID = "bt-gl-raid"
	local key = ID .. "-y"
	local c, i, sp
	ctx.at(5, gleba)
	ctx.at(2000, function()
		local surface = game.surfaces.gleba
		loop.ground(-T, -16, T, 32, "gleba")
		-- a gleba-spawner collides with ground tiles (spike 34 G3): it stands on a wetland patch
		local tiles = {}
		for x = -48, -33 do
			for y = 0, 15 do
				tiles[#tiles + 1] = { name = "wetland-blue-slime", position = { x, y } }
			end
		end
		surface.set_tiles(tiles)
		border.rebuild()
		loop.sync()
		loop.edge(ID, T, {}, { T / 2, -T / 2, 4 }, { -T / 2, T / 2, 12 }, "gleba")
		ctx.expect(surface.create_entity({ name = "gleba-spawner", position = { -40, 8 }, force = "enemy" }) ~= nil, "spawner stands")
		-- the raid's own target: two agricultural towers (spore emitters by prototype, powered or not) in one chunk, so
		-- they are the densest on Gleba whatever the oracle case's towers (one a chunk) stand at
		for _, p in ipairs(TOWERS) do
			surface.create_entity({ name = "agricultural-tower", position = p, force = "player" })
		end
		cloud.index("gleba")
	end)
	ctx.at(2060, function()
		local surface = game.surfaces.gleba
		c = cloud.state("gleba")
		i = cloud_core.index(storage.gridworld.tiles.gleba, -2, 0)
		c.grids = { [key] = { route = key, v = { [i] = 1000 }, x = 48, top = 0, stamp = 0 } } -- fixture: no real leak in it
		sp = select(2, next(c.spawners))
		sp.pool = 0
		ctx.expect(sp ~= nil and sp.i == i, "the spawner is indexed in its chunk")
		-- a fixture detail if it fails: the filter must leave a unit with weight at Gleba's evolution here
		local units = {}
		for _, ru in ipairs(sp.e.prototype.result_units) do
			units[#units + 1] = ru.unit
		end
		ctx.expect(#cloud_core.weights(sp.e.prototype.result_units, game.forces.enemy.get_evolution_factor(surface)) > 0,
			"units with weight at evolution " .. game.forces.enemy.get_evolution_factor(surface) .. ": " .. table.concat(units, ","))
		cloud.budget("gleba", game.tick)
		ctx.expect(math.abs(sp.pool - 30) < 1e-6 and math.abs(c.grids[key].v[i] - 970) < 1e-6,
			"took 20 + 0.01 x 1000 = 30; pool " .. sp.pool)
		ctx.expect(sp.raid ~= nil, "gathering")
	end)
	landed(ctx, 2100, function(found)
		ctx.expect(#found > 0, "the raid came out by the east line")
		local wrigglers = 0
		for _, e in ipairs(found) do
			local ai = e.prototype.ai_settings
			wrigglers = wrigglers + ((e.name:find("wriggler", 1, true) or (ai and ai.join_attacks == false)) and 1 or 0)
		end
		ctx.expect(wrigglers == 0, "every unit joins attacks; " .. wrigglers .. " don't")
		local group = found[1] and found[1].commandable and found[1].commandable.parent_group
		local cmd = group and group.command
		local d, hit = cmd and cmd.destination, false
		for _, p in ipairs(TOWERS) do
			hit = hit or (d ~= nil and math.abs(d.x - p[1]) < 1.5 and math.abs(d.y - p[2]) < 1.5)
		end
		ctx.expect(cmd and cmd.type == defines.command.attack_area and hit, "attack_area at this case's own tower; got "
			.. serpent.line(cmd and { cmd.type, d }))
	end)
	ctx.expect_ipc("gridworld:out", '"phase":"formed"')
end)
